-- =============================================================================
-- ОТКРЫТИЕ / ЗАКРЫТИЕ МЕНЮ (плавное увеличение из центра, без рывков)
-- =============================================================================
local menuOpen, busy = false, false

local function openMenu()
    if menuOpen or busy then return end
    busy, menuOpen = true, true
    play("Open")

    MainScale.Scale = 0.02
    Holder.Visible = true

    local t = tw(MainScale, TweenInfo.new(0.5, Enum.EasingStyle.Quint, Enum.EasingDirection.Out), {Scale = 1})
    t.Completed:Connect(function() busy = false end)
    task.delay(0.8, function() busy = false end)
end

local function closeMenu()
    if not menuOpen or busy then return end
    busy, menuOpen = true, false
    play("Close")

    local t = tw(MainScale, TweenInfo.new(0.28, Enum.EasingStyle.Quad, Enum.EasingDirection.In), {Scale = 0.02})
    t.Completed:Connect(function()
        if not menuOpen then Holder.Visible = false end
        busy = false
    end)
    task.delay(0.6, function() busy = false end)
end

local function toggleMenu()
    if menuOpen then closeMenu() else openMenu() end
end

makeDraggable(FloatBtn, FloatBtn, function()
    toggleMenu()
end)

MenuBtn.MouseButton1Click:Connect(function()
    closeMenu()
end)

UserInputService.InputBegan:Connect(function(input, gameProcessed)
    if not gameProcessed and input.KeyCode == CONFIG.ToggleKey then
        toggleMenu()
    end
end)

-- =============================================================================
-- ИНТРО: чёрный экран, красная Z, надпись
-- =============================================================================
local function runIntro()
    local Intro = Instance.new("Frame")
    Intro.Name = "Intro"
    Intro.Size = UDim2.new(1, 0, 1, 0)
    Intro.BackgroundColor3 = Color3.fromRGB(0, 0, 0)
    Intro.BackgroundTransparency = 0 -- сразу полностью чёрный, без прозрачности
    Intro.BorderSizePixel = 0
    Intro.Active = true
    Intro.ZIndex = 50
    Intro.Parent = ScreenGui

    local ok = pcall(function()
        local Group = Instance.new("Frame")
        Group.AnchorPoint = Vector2.new(0.5, 0.5)
        Group.Position = UDim2.new(0.5, 0, 0.5, 0)
        Group.Size = UDim2.new(0, 500, 0, 200)
        Group.BackgroundTransparency = 1
        Group.ZIndex = 51
        Group.Parent = Intro

        local vp = Camera.ViewportSize
        local GS = Instance.new("UIScale")
        GS.Scale = math.clamp(math.min(vp.X / 460, vp.Y / 190), 0.5, 1.5)
        GS.Parent = Group

        local LOGO_H = 120
        local GAP = 20
        local logo, lw = buildZ(Group, LOGO_H)
        logo.AnchorPoint = Vector2.new(0.5, 0.5)
        logo.Position = UDim2.new(0.5, 0, 0.5, 0)
        logo.GroupTransparency = 1
        logo.ZIndex = 54

        local LogoScale = Instance.new("UIScale")
        LogoScale.Scale = 0.5
        LogoScale.Parent = logo

        local tws = TextService:GetTextSize(CONFIG.IntroText, CONFIG.IntroTextSize,
            CONFIG.IntroFont, Vector2.new(1000, 200)).X + 6

        local total = lw + GAP + tws
        local logoEnd = -total / 2 + lw / 2         -- центр логотипа после сдвига
        local wordEnd = -total / 2 + lw + GAP       -- левый край надписи в конце
        local wordStart = -lw * 0.2                 -- откуда надпись "выходит"

        local Word = Instance.new("TextLabel")
        Word.AnchorPoint = Vector2.new(0, 0.5)
        Word.Position = UDim2.new(0.5, wordStart, 0.5, 0)
        Word.Size = UDim2.new(0, tws, 0, CONFIG.IntroTextSize + 16)
        Word.BackgroundTransparency = 1
        Word.Text = CONFIG.IntroText
        Word.Font = CONFIG.IntroFont
        Word.TextSize = CONFIG.IntroTextSize
        Word.TextColor3 = Color3.fromRGB(255, 255, 255)
        Word.TextTransparency = 1
        Word.TextXAlignment = Enum.TextXAlignment.Left
        Word.ZIndex = 53
        Word.Parent = Group

        -- 1. появление Z
        task.wait(0.25)
        play("Intro")
        tw(logo, TweenInfo.new(0.7, Enum.EasingStyle.Quad), {GroupTransparency = 0})
        tw(LogoScale, TweenInfo.new(0.9, Enum.EasingStyle.Quint, Enum.EasingDirection.Out), {Scale = 1})
        task.wait(1.3)

        -- 2. Z уезжает влево, из неё выходит надпись
        play("Slide")
        local slide = TweenInfo.new(1.0, Enum.EasingStyle.Quint, Enum.EasingDirection.InOut)
        tw(logo, slide, {Position = UDim2.new(0.5, logoEnd, 0.5, 0)})
        task.delay(0.15, function()
            tw(Word, slide, {Position = UDim2.new(0.5, wordEnd, 0.5, 0), TextTransparency = 0})
        end)
        task.wait(2.1)

        -- 3. надпись заходит обратно, Z возвращается
        play("Slide", 0.85)
        tw(Word, slide, {Position = UDim2.new(0.5, wordStart, 0.5, 0), TextTransparency = 1})
        task.delay(0.15, function()
            tw(logo, slide, {Position = UDim2.new(0.5, 0, 0.5, 0)})
        end)
        task.wait(1.3)

        -- 4. чёрный экран и буква плавно исчезают
        local fade = TweenInfo.new(0.6, Enum.EasingStyle.Quad)
        tw(Intro, fade, {BackgroundTransparency = 1})
        tw(logo, fade, {GroupTransparency = 1})
        task.wait(0.6)
    end)

    Intro:Destroy()
    return ok
end

task.spawn(function()
    runIntro()

    FloatBtn.Visible = true
    tw(FloatBtnScale, TweenInfo.new(0.4, Enum.EasingStyle.Quint, Enum.EasingDirection.Out), {Scale = 1})

    openMenu()
end)
