local B64 = {}
do
    local chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    for i = 1, #chars do B64[chars:byte(i)] = i - 1 end
end

local function b64decode(s)
    s = s:gsub("%s", "")
    local out, o = {}, 0
    for i = 1, #s, 4 do
        local c1, c2, c3, c4 = s:byte(i, i + 3)
        local v1, v2 = B64[c1] or 0, B64[c2] or 0
        local v3, v4 = B64[c3], B64[c4]
        local n = v1 * 262144 + v2 * 4096 + (v3 or 0) * 64 + (v4 or 0)
        o = o + 1
        out[o] = string.char(math.floor(n / 65536) % 256)
        if v3 then
            o = o + 1
            out[o] = string.char(math.floor(n / 256) % 256)
        end
        if v4 then
            o = o + 1
            out[o] = string.char(n % 256)
        end
    end
    return table.concat(out)
end

local soundIds = {}

local function prepareSounds()
    local gca = getcustomasset or getsynasset
    if writefile and gca then
        for name, b64 in pairs(SOUND_B64) do
            pcall(function()
                local path = "zynth_" .. name .. ".ogg"
                writefile(path, b64decode(b64))
                soundIds[name] = gca(path)
            end)
        end
    end
    for name, id in pairs(CONFIG.CustomSounds) do
        soundIds[name] = id
    end
end
prepareSounds()

local function play(name, speedMul)
    local id = soundIds[name]
    if not id then return end
    pcall(function()
        local s = Instance.new("Sound")
        s.SoundId = id
        s.Volume = SOUND_VOL[name] or 0.6
        local speed = speedMul or 1
        if SOUND_VARY[name] then speed = speed * (0.96 + math.random() * 0.09) end
        s.PlaybackSpeed = speed
        s.Parent = SoundService
        s:Play()
        Debris:AddItem(s, 6)
    end)
end

